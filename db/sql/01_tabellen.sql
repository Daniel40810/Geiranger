  GEAENDERT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT GR_QUELLE_PK PRIMARY KEY (ID),
  CONSTRAINT GR_QUELLE_UK UNIQUE (KURZ),
  CONSTRAINT GR_QUELLE_ART_CK CHECK (ART IN ('WEB','BUCH','ARTIKEL','DATEN','MESSUNG','APP')),
  CONSTRAINT GR_QUELLE_HERKUNFT_CK CHECK (HERKUNFT IN ('MITGELIEFERT','EIGEN'))
);

CREATE OR REPLACE TRIGGER GR_QUELLE_BIU
BEFORE INSERT OR UPDATE ON GR_QUELLE
FOR EACH ROW
BEGIN
  IF INSERTING THEN
    IF :NEW.ID IS NULL THEN
      :NEW.ID := GR_QUELLE_SEQ.NEXTVAL;
    END IF;
    :NEW.ANGELEGT := NVL(:NEW.ANGELEGT, SYSTIMESTAMP);
  END IF;
  :NEW.GEAENDERT := SYSTIMESTAMP;
END;
