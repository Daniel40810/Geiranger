-- Schema GEIRANGER auf PDBORCL, Präfix GR_. Werkbuch Abschnitt 8, freigegeben am 24.10.2026 (F25–F37 „alle A“).
--
-- Wiederholbar: Was schon da ist, meldet Oracle mit ORA-00955 (Name schon vergeben); der Einrichter der App
-- übergeht genau diese Meldung. In SQL Developer als Skript ausführen (F5); die Meldungen bei einem zweiten
-- Lauf sind dann harmlos. Dieses Skript löscht nichts.
--
-- Hauskonvention: ID aus Sequence + Trigger, nie GENERATED AS IDENTITY. Je Spalte eine Zeile, damit der
-- Einrichter fehlende Spalten erkennen und nachtragen kann. Lage in 8307 (WGS 84, Länge vor Breite, F28 A),
-- daneben Szenenmeter X_M, Y_M, Z_M (x nach Osten, z nach Süden, y über NN; Ursprung am Anleger, F2; die Szene
-- rechnet in UTM 32 N, EPSG 25832, E 406 330, N 6 886 760).
-- Szenenzeit: SZENE_MS = Millisekunden seit 1970 (UTC) wie die Uhr der App; SZENE_TEXT so, wie die App sie zeigt
-- („21.06.2026 09:10 MESZ“); SZENE_TAG = 'JJJJ-MM-TT' für Filter. Alle Daten der Szene liegen nach 1583; darum setzt
-- der Trigger zusätzlich SZENENZEIT als TIMESTAMP WITH TIME ZONE in Europe/Oslo.
-- HERKUNFT: MITGELIEFERT stellt der Einrichter bei jedem Lauf wieder her (04_startdaten.sql), EIGEN fasst er nie an.
-- 36 Tabellen in neun Themen: Betrieb, Quellen, Gelände, Wasser, Klima und Jahr, Straße und Ort, Schiffe, Regie
-- und Chronik, Kamera, Eigenes und Packages.
-- =====================================================================================================


-- -----------------------------------------------------------------------------------------------------
