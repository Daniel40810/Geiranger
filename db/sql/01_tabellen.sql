-- -----------------------------------------------------------------------------------------------------
CREATE TABLE GR_SCHEMA (
  VERSION      NUMBER(4) NOT NULL,
  EINGERICHTET TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  APP_VERSION  VARCHAR2(20 CHAR) NOT NULL,
  TEXT         VARCHAR2(400 CHAR),
  CONSTRAINT GR_SCHEMA_PK PRIMARY KEY (VERSION)
);


-- -----------------------------------------------------------------------------------------------------
-- GR_QUELLE: Quellen zum Vorbild (Werkbuch Abschnitt 14), Daten (HGT-Kacheln) und die App selbst (APP: gestaltet).
-- -----------------------------------------------------------------------------------------------------
